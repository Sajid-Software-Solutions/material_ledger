/// Centralized copy for the protected scoped-permission workspace.
///
/// Capability keys are server-owned. Known modules/actions receive polished
/// translations; a future catalogue entry falls back to a readable label
/// without making the client reject the otherwise valid server projection.
abstract final class YorksV1PermissionStrings {
  static String text(AppLanguage language, String key, {String? fallback}) =>
      _localized[language.code]?[key] ??
      _english[key] ??
      fallback ??
      _readable(key);

  static String module(AppLanguage language, String module) =>
      text(language, 'module.$module', fallback: _readable(module));

  static String action(AppLanguage language, String action) =>
      text(language, 'action.$action', fallback: _readable(action));

  static String role(AppLanguage language, YorksV1Role? role) => role == null
      ? text(language, 'unassigned')
      : text(
          language,
          'role.${role.claimValue}',
          fallback: _readable(role.claimValue),
        );

  static String effect(
    AppLanguage language,
    YorksV1PermissionAssignmentEffect effect,
  ) => text(language, 'effect.${effect.wireValue}');

  static String source(
    AppLanguage language,
    YorksV1PermissionEffectiveSource source,
  ) => text(language, 'source.${source.wireValue}');

  static String risk(AppLanguage language, YorksV1PermissionRiskLevel risk) =>
      text(language, 'risk.${risk.wireValue}');

  static String scope(AppLanguage language, YorksV1PermissionScopeKind scope) =>
      text(language, 'scope.${scope.wireValue}');

  static String historyKind(
    AppLanguage language,
    YorksV1PermissionHistoryEventKind kind,
  ) => text(language, 'history.${kind.wireValue}');

  static String _readable(String raw) {
    final words = raw
        .replaceAll('.', ' ')
        .replaceAll('_', ' ')
        .trim()
        .split(RegExp(r'\s+'))
        .where((word) => word.isNotEmpty)
        .toList(growable: false);
    if (words.isEmpty) return raw;
    return words
        .map((word) => '${word[0].toUpperCase()}${word.substring(1)}')
        .join(' ');
  }


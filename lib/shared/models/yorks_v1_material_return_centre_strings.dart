  YorksV1ProjectMaterialReturnState state,
) => switch (state) {
  YorksV1ProjectMaterialReturnState.draft ||
  YorksV1ProjectMaterialReturnState.returnedForChanges =>
    const TranslatableString(
      en: 'Creator',
      ar: 'المنشئ',
      ur: 'تخلیق کار',
      hi: 'निर्माता',

  YorksV1ProjectMaterialReturnState.confirmed ||
  YorksV1ProjectMaterialReturnState.rejected ||
  YorksV1ProjectMaterialReturnState.cancelled => const TranslatableString(
    en: 'No one',
    ar: 'لا أحد',

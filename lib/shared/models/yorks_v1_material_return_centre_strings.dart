  YorksV1ProjectMaterialReturnState.awaitingApproval =>
    const TranslatableString(
      en: 'Engineering',
      ar: 'الهندسة',
      ur: 'انجینئرنگ',
      hi: 'इंजीनियरिंग',
    ),
  YorksV1ProjectMaterialReturnState.approved => const TranslatableString(
    en: 'Project team',
    ar: 'فريق المشروع',
    ur: 'پروجیکٹ ٹیم',
    hi: 'परियोजना टीम',
  ),
  YorksV1ProjectMaterialReturnState.dispatched => const TranslatableString(
    en: 'Procurement / warehouse',
    ar: 'المشتريات / المستودع',
    ur: 'خریداری / گودام',
    hi: 'खरीद / गोदाम',
